static unsigned char const colors[4][3] = { { 230, 230, 230 }, { 40, 200, 60 }, { 220, 40, 40 }, { 40, 60, 220 } };

static int near(int a, int b) { return a - b <= 12 && b - a <= 12; }

int main(void)
{
    char const *codec = avifCodecName(AVIF_CODEC_CHOICE_AUTO, AVIF_CODEC_FLAG_CAN_DECODE);
    if (!codec || strcmp(codec, "dav1d") != 0) {
        printf("the AV1 decoder is %s, not dav1d\n", codec ? codec : "missing");
        return 1;
    }

    avifDecoder *decoder = avifDecoderCreate();
    avifImage *image = avifImageCreateEmpty();
    avifResult result = avifDecoderReadMemory(decoder, image, image_avif, sizeof image_avif);
    if (result != AVIF_RESULT_OK) {
        printf("avifDecoderReadMemory: %s\n", avifResultToString(result));
        return 1;
    }
    if (image->width != 32 || image->height != 32 || image->depth != 8) {
        printf("decoded %ux%u of %u bits\n", image->width, image->height, image->depth);
        return 1;
    }

    avifRGBImage rgb;
    avifRGBImageSetDefaults(&rgb, image);
    rgb.format = AVIF_RGB_FORMAT_RGB;
    if ((result = avifRGBImageAllocatePixels(&rgb)) != AVIF_RESULT_OK || (result = avifImageYUVToRGB(image, &rgb)) != AVIF_RESULT_OK) {
        printf("avifImageYUVToRGB: %s\n", avifResultToString(result));
        return 1;
    }
    /* the middle of each quadrant comes back close to its colour */
    for (int q = 0; q < 4; ++q) {
        unsigned char const *pixel = rgb.pixels + ((q / 2) * 16 + 8) * rgb.rowBytes + ((q % 2) * 16 + 8) * 3;
        if (!near(pixel[0], colors[q][0]) || !near(pixel[1], colors[q][1]) || !near(pixel[2], colors[q][2])) {
            printf("quadrant %d came back as %d,%d,%d\n", q, pixel[0], pixel[1], pixel[2]);
            return 1;
        }
    }
    avifRGBImageFreePixels(&rgb);
    avifImageDestroy(image);
    avifDecoderDestroy(decoder);

    char codecs[256];
    avifCodecVersions(codecs);
    printf("libavif %s (%s): %u bytes to 32x32 RGB\n", avifVersion(), codecs, (unsigned)sizeof image_avif);
    puts("ok");
    return 0;
}
